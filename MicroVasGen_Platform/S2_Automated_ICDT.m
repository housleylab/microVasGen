% =========================================================================
% Title:        Murray's Law Vessel Diameter Assignment via Electrical
%               Network Analogy (END Approach)
% Author:       Aref Valipour, Housley Lab, Georgia Tech
% Date:         2026
%
% Description:
%   Implements the Electrical Network Dynamics (END) approach to assign
%   physiologically realistic vessel diameters to a microvascular network
%   graph. The method exploits Murray's Law, which states that vessel
%   diameter scales with the cube root of volumetric flow rate:
%
%       d ∝ Q^(1/3)
%
%   The hydraulic analogy maps blood flow (Q) to electric current (I) and
%   vascular resistance to electrical resistance. Each vessel segment is
%   assigned a uniform resistance of 1 Ω, so the current distribution
%   produced by LTspice reflects the relative flow rates throughout the
%   network. Diameters are then derived as:
%
%       d_i  ∝  |I_i|^(1/3)
%
%   After normalisation, a lower-bound threshold clips unrealistically
%   narrow segments (capillaries below a biologically plausible minimum),
%   and a global scale factor maps the dimensionless diameters to physical
%   units (mm).
%
% Workflow:
%   1. Load a network graph generated by generateMicrovascularNetwork.m
%   2. Write a SPICE netlist (uniform-resistance topology)
%   3. Run LTspice in batch mode to compute nodal voltages and branch currents
%   4. Parse the LTspice .raw binary output
%   5. Apply Murray's Law (d ∝ I^1/3), normalise, threshold, and scale
%   6. Save the updated network with electrically-assigned diameters
%   7. Plot a histogram of the final diameter distribution
%
% Inputs:
%   ./Models/<modelName>.mat     Network graph produced by the generator script
%                              (variables: nodes, segments, segment_diameters,
%                               domain_size, branch_angles)
%
% Outputs:
%   ./Electrical/<modelName>_murray.txt     SPICE netlist (plain text)
%   ./Electrical/<modelName>_murray.raw     LTspice simulation results
%   ./Models/<modelName>_ICDT.mat     Network with updated diameters
%
% Dependencies:
%   LTspice (ADI)              External circuit simulator — must be installed.
%                              Update ltspicePath in the Parameters section.
%   LTspice2Matlab             MATLAB function for parsing .raw binary files.
%                              Paul Wagner (2026). Fast Import of Compressed 
%                              Binary .RAW Files Created with LTspice Circuit 
%                              Simulator (https://www.mathworks.com/matlabcentral/fileexchange/23394-fast-import-of-compressed-binary-raw-files-created-with-ltspice-circuit-simulator), 
%                              MATLAB Central File Exchange. Retrieved March 5, 2026.
%
% Citation:
%   Valipour, A., Bourque, A. R. & Housley, S. N. Integrated Framework for Modeling Microvascular Networks. Nat. Commun. (2026, in press).
%   Preprint: Valipour, A., Bourque, A. R. & Housley, S. N. Integrated framework for multiscale microvascular models. 
%   bioRxiv https://doi.org/10.64898/2026.04.13.718340 (2026).
% =========================================================================

%% --- Workspace Initialization -------------------------------------------
clear;
close all;
clc;


%% --- Parameters ---------------------------------------------------------

% --- File and model identity ---
modelName = "model_1";   % Name of the network file (without extension)
                                %   Must match a file in ./Models/<modelName>.mat

% --- SPICE simulation ---
% Uniform resistance assigned to every vessel segment (Ω).
% Because all resistances are equal, the current distribution encodes
% relative flow rates directly — analogous to setting all hydraulic
% resistances to the same value so that topology alone governs flow.
uniformResistanceOhm = 1;

% Full path to the LTspice executable.
ltspicePath = '"D:/Program Files/ADI/LTspice/LTspice.exe"';

% --- Unit conversion ---
% The network generator stores diameters in mm. The factor below converts
% to metres for physical consistency with downstream models (if needed).
% Set to 1 to keep all values in mm.
diameterUnitConversion = 0.001;   % mm → m

% --- Murray's Law exponent ---
% Murray's Law: d ∝ Q^murrayExponent, where Q is volumetric flow rate.
% The theoretical value is 1/3 (cube-root law for optimal bifurcation).
murrayExponent = 3;

% --- Diameter normalisation and thresholding ---
% After Murray's Law scaling, diameters are normalised by their mean.
% Segments whose normalised diameter falls below the threshold are clamped
% to the threshold value (representing the minimum capillary diameter).
% threshold = 1 - thresholdStdMultiplier * std(normalised diameters)
thresholdStdMultiplier = 0;   % Number of standard deviations below mean
                                  %   at which to apply the lower-bound clamp.
                                  %   Increase to preserve more thin vessels;
                                  %   decrease to clamp more aggressively.
                                  %   Set at 0 for no thresholding

% --- Physical diameter scale-up ---
% Maps the normalised (dimensionless) diameter distribution to physical
% units after clamping. Components:
%   targetMaxDiameter_m    : target maximum vessel diameter in metres
%   thresholdCorrectionFactor : corrects for the fraction of vessels that
%                               were clamped (~25% in typical networks)
%   diameterUnitConversion : mm→m conversion (same as above)
% The formula ensures that a vessel at the threshold normalised value maps
% to approximately targetMaxDiameter_m in physical units.
targetMaxDiameter_m         = 25;        % Desired scale reference in micron (to map the mean)
thresholdCorrectionFactor   = 1;        % Any required fabrication correction 
diameterScaleFactor = targetMaxDiameter_m * thresholdCorrectionFactor * diameterUnitConversion;



%% --- Load Network Graph -------------------------------------------------
% Loads the node coordinates, segment connectivity, and initial diameter
% estimates produced by the network generator.

load(append("./Models/", modelName, ".mat"));


%% --- Identify Outlet Node -----------------------------------------------
% The outlet is the node with the largest x-coordinate (rightmost node).
% In the SPICE netlist this node will be driven by the voltage source.
% MATLAB node indices are 1-based; SPICE node labels are 0-based, so
% SPICE node = MATLAB node index − 1.

[~, outletNodeIdx] = max(networkNodes(:, 1));


%% --- Generate SPICE Netlist ---------------------------------------------
% Each vessel segment is modelled as a resistor (R = uniformResistanceOhm).
% A 1 V DC voltage source is applied between ground (SPICE node 0) and
% the outlet node. The resulting branch currents encode relative flow rates.
%
% Netlist format (standard SPICE syntax):
%   * <comment>
%   V<name> <node+> <node-> <value>
%   R<name> <node1> <node2> <value>
%   .op         — DC operating point analysis
%   .print dc   — print DC node voltages
%   .end

spiceNetlist = ["*"];
spiceNetlist = [spiceNetlist; "V1 0 " + num2str(outletNodeIdx - 1) + " 1;"];

for i = 1:size(networkSegments, 1)
    % All segments assigned the same resistance so that current ∝ flow
    spiceNetlist = [spiceNetlist; ...
        "R" + num2str(i) + " " + num2str(networkSegments(i,1)-1) + ...
        " " + num2str(networkSegments(i,2)-1) + " " + uniformResistanceOhm + ";"];
end

spiceNetlist = [spiceNetlist; ".op;"];
spiceNetlist = [spiceNetlist; ".print dc V(1);"];
spiceNetlist = [spiceNetlist; ".end"];

netlistFilePath = append("./electrical/", modelName, "_ICDT.txt");
writematrix(spiceNetlist, netlistFilePath);

fprintf('SPICE netlist written to: %s\n', netlistFilePath);


%% --- Run LTspice Simulation ---------------------------------------------
% LTspice is invoked in batch mode (-b) so it runs without a GUI and writes
% results to a binary .raw file that is parsed in the next section.

pause(0.5);     % Brief pause to ensure the netlist file is fully flushed to disk

spiceCommand = sprintf('%s -b -run %s', ltspicePath, netlistFilePath);
[spiceStatus, spiceOutput] = system(spiceCommand);

if spiceStatus ~= 0
    fprintf('LTspice command: %s\n', spiceCommand);
    fprintf('LTspice output:\n%s\n', spiceOutput);
    error('LTspice simulation failed. Verify ltspicePath in the Parameters section.');
end

pause(0.5);     % Brief pause to ensure LTspice has finished writing the .raw file


%% --- Parse LTspice .raw Output ------------------------------------------
% LTspice2Matlab reads the binary .raw file and returns a struct with
% variable names, types, and values from the DC operating-point analysis.

rawFilePath = append("./electrical/", modelName, "_ICDT.raw");
ltspiceData = LTspice2Matlab(rawFilePath);

% Count voltage and current variables in the output
voltageCount = sum(strcmp(ltspiceData.variable_type_list, 'voltage'));
currentCount = ltspiceData.num_variables - voltageCount - 1;

% --- Extract nodal voltages ----------------------------------------------
% Seed the list with the ground node (MATLAB index 1, voltage = 0 V).
% LTspice node 0 = MATLAB node 1.
nodeVoltages(1, 1) = 1;     % MATLAB node index
nodeVoltages(1, 2) = 0;     % Voltage (V) — ground reference

for i = 1:voltageCount
    % Variable names are formatted as "V(<spice_node>)"; extract the integer
    % node label and convert back to MATLAB 1-based indexing.
    nodeVoltages(i+1, 1) = str2double( ...
        extractBetween(string(ltspiceData.variable_name_list(i)), "(", ")")) + 1;
    nodeVoltages(i+1, 2) = ltspiceData.variable_mat(i);
end

nodeVoltages = sortrows(nodeVoltages);  % Sort by node index for easy lookup

% --- Extract segment (branch) currents -----------------------------------
% LTspice reports one current per resistor (I(R<n>)) plus one current for
% the voltage source (I(V1)). The voltage source current entry shifts the
% indexing of the resistor currents by one position in the variable list,
% so we track whether I(V1) has already been encountered.

foundSourceCurrent = 0;     % Flag: 1 once I(V1) has been found in the list
skipOffsetActive   = 0;     % Flag: 1 once the index offset must be applied

for i = 1:currentCount + 1
    varName = string(ltspiceData.variable_name_list(i + voltageCount));

    if contains(varName, 'I(V')
        % This entry is the voltage source current — record it and set flags
        sourceCurrentMagnitude = abs(ltspiceData.variable_mat(i + voltageCount));
        foundSourceCurrent = 1;

    elseif skipOffsetActive == 1
        % I(V1) was already found: resistor index in the list is offset by 1
        extractedIdx = extractBetween(varName, "I(R", ")");
        segmentCurrents(i-1, 1) = str2double(extractedIdx{1});
        segmentCurrents(i-1, 2) = ltspiceData.variable_mat(i + voltageCount);

    else
        % I(V1) not yet encountered: no index offset needed
        extractedIdx = extractBetween(varName, "I(R", ")");
        segmentCurrents(i, 1) = str2double(extractedIdx{1});
        segmentCurrents(i, 2) = ltspiceData.variable_mat(i + voltageCount);
    end

    if foundSourceCurrent == 1
        skipOffsetActive = 1;
    end
end

segmentCurrents = sortrows(segmentCurrents);   % Sort by segment index


%% --- Murray's Law Diameter Assignment -----------------------------------
% Apply Murray's Law: vessel diameter scales with the cube root of flow rate.
% Since current ∝ flow rate in the electrical analogy:
%
%       d_i  ∝  |I_i|^(1/3)
%
% Steps:
%   1. Raise absolute current to the power murrayExponent (= 3)
%   2. Normalise by the minimum nonzero value so the smallest vessel = 1
%   3. Normalise again by the mean (bias correction) to get a
%      mean-centred distribution with mean = 1
%   4. Clamp values below the threshold to the threshold (minimum capillary)
%   5. Apply a global scale factor to convert to physical units

% Step 1: Murray's Law scaling
diameterCurrentMap       = segmentCurrents;
diameterCurrentMap(:, 2) = abs(segmentCurrents(:, 2)).^(1/murrayExponent);

% Step 2: Normalise by the minimum nonzero scaled current
%         (ensures the narrowest vessel gets a relative diameter of 1)
minNonzeroScaled         = min(diameterCurrentMap(diameterCurrentMap(:,2) > 0, 2));
diameterCurrentMap(:, 2) = abs(diameterCurrentMap(:, 2) / minNonzeroScaled);

% Compute distribution statistics before bias correction
diameterMapStd  = std(diameterCurrentMap(:, 2));
diameterMapMean = mean(diameterCurrentMap(:, 2));

% Step 3: Normalise by the mean (bias correction → mean of distribution = 1)
normalizedDiameters       = diameterCurrentMap;
normalizedDiameters(:, 2) = normalizedDiameters(:, 2) / diameterMapMean;


% Step 5: Scale to physical units.
% effective scale = diameterScaleFactor / diameterThreshold
% This ensures a vessel at exactly the threshold value maps to the
% intended minimum physical diameter.
effectiveScaleFactor  = diameterScaleFactor;
normalizedDiameters(:, 2) = normalizedDiameters(:, 2) * effectiveScaleFactor;

% Step 4: Compute and apply the lower-bound threshold.
% Segments below the threshold represent physiologically implausible
% capillaries and are clamped to the threshold value.
% threshold = 1 - thresholdStdMultiplier * std(normalised diameters)
if thresholdStdMultiplier == 0
diameterThreshold = 0;
else
diameterThreshold = (mean(normalizedDiameters(:, 2)) - thresholdStdMultiplier * std(normalizedDiameters(:, 2)));
end

clampedSegmentCount = 0;
for i = 1:size(normalizedDiameters, 1)
    if normalizedDiameters(i, 2) < diameterThreshold
        normalizedDiameters(i, 2) = diameterThreshold;
        clampedSegmentCount = clampedSegmentCount + 1;
    end
end

% Report what fraction of segments were clamped
percentClampedDiameters = clampedSegmentCount * 100 / size(segmentDiameters, 1)



% Update segment diameters with the electrically-assigned values
segmentDiameters = normalizedDiameters(:, 2);


%% --- Save Results -------------------------------------------------------
% Save the updated network with the new physically-scaled diameters.
% Diagnostic parameters (threshold, scale factor, distribution statistics)
% are also saved for reproducibility and downstream reporting.

outputFile = append("./Models/", modelName, "_ICDT.mat");
save(outputFile, 'networkNodes', 'networkSegments', 'segmentDiameters', ...
    'domainSize', 'diameterThreshold', 'effectiveScaleFactor', ...
    'diameterMapStd', 'diameterMapMean');

fprintf('Electrically-assigned network saved to: %s\n', outputFile);


%% --- Visualisation: Diameter Distribution -------------------------------
% Histogram of the final assigned diameters converted to µm for
% readability. Useful for verifying the distribution is physiologically
% plausible (typical capillary range: ~5–20 µm; arterioles: ~20–200 µm).

histogram(normalizedDiameters(:, end) * 1000);
xlabel('Vessel Diameter (µm)');
ylabel('Number of Segments');
title('Murray''s Law Diameter Distribution');

minimumDiameter = min(normalizedDiameters(:, end));
disp(minimumDiameter)